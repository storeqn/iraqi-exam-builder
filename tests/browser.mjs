import assert from 'node:assert/strict'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { chromium } from 'playwright'
import JSZip from 'jszip'
import { preview } from 'vite'

const base='http://127.0.0.1:4179/'
const server=await preview({configFile:false,preview:{host:'127.0.0.1',port:4179,strictPort:true}})
const errors=[]
let browser
try {
  const options={headless:true,executablePath:process.env.TEST_CHROMIUM_PATH||undefined,args:['--no-sandbox']}
  if(process.env.TEST_CHROMIUM_SINGLE_PROCESS)options.args.push('--single-process','--no-zygote','--disable-dev-shm-usage')
  browser=await chromium.launch(options)
  const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true,reducedMotion:'reduce'})
  const page=await context.newPage()
  page.on('pageerror',error=>errors.push(error.message))
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text())})
  page.on('dialog',dialog=>void dialog.accept())
  const button=(label)=>page.getByRole('button',{name:label,exact:true})
  const write=async(download)=>{
    const path=await download.path()
    return readFile(path)
  }
  await page.goto(base)
  await page.getByRole('heading',{name:'ورقتك الامتحانية، بتنسيق يليق بصفّك.'}).waitFor()
  assert.equal(await page.locator('html').getAttribute('dir'),'rtl')
  if(process.env.TEST_OUTPUT){await mkdir(process.env.TEST_OUTPUT,{recursive:true});await page.screenshot({path:process.env.TEST_OUTPUT+'/dashboard.png',fullPage:true})}
  await button('إنشاء ورقة امتحانية جديدة').click()
  await page.getByLabel('عنوان الورقة المطبوع').fill('امتحان الرياضيات')
  assert.equal(await page.locator('.print-root .sheet-center strong').first().textContent(),'امتحان الرياضيات')
  await page.getByLabel('المادة',{exact:true}).fill('الرياضيات')
  await page.getByLabel('اسم المدرسة',{exact:true}).fill('مدرسة القرنة')
  const headerAlignment=columns=>columns.map(column=>getComputedStyle(column).textAlign)
  assert.deepEqual(await page.locator('.preview-viewport .sheet-header > div').evaluateAll(headerAlignment),['center','center','center'])
  assert.deepEqual(await page.locator('.print-root [data-sheet]:first-of-type .sheet-header > div').evaluateAll(headerAlignment),['center','center','center'])
  await page.locator('summary').filter({hasText:'تفاصيل إضافية'}).click()
  await page.getByLabel('الدرجة الكلية').fill('40')
  await button('الانتقال إلى الأسئلة').click()
  await button('إضافة أول سؤال').click()
  const rich=page.getByRole('textbox',{name:'نص السؤال',exact:true})
  assert.ok(await rich.evaluate(element=>document.activeElement===element))
  await rich.fill('احسب القيمة عند x = 3.')
  await page.getByLabel('درجة السؤال').fill('40')
  await rich.press('End')
  await button('معادلة').click()
  await button('كسر').click()
  assert.match(await page.locator('math-field').evaluate(field=>field.value),/frac/)
  await button('عرض LaTeX').click()
  await page.getByLabel('LaTeX',{exact:true}).fill('\\frac{1}{2}+x^2')
  await button('حفظ المعادلة').click()
  await page.locator('.editable [data-equation]').waitFor()
  await button('معادلة').click()
  await button('عرض LaTeX').click()
  await page.getByLabel('LaTeX',{exact:true}).fill(String.raw`\begin{pmatrix}1&2\\3&4\end{pmatrix}`)
  await button('حفظ المعادلة').click()
  assert.equal(await page.locator('.editable [data-equation]').count(),2)
  await button('إدراج جدول').click()
  await button('إدراج الجدول').click()
  await page.locator('.editable table').waitFor()
  await page.locator('.editable td').first().click()
  await page.keyboard.insertText('اختبار الجدول')
  await button('رسم هندسي').click()
  await button('إضافة شكل').click()
  await page.getByLabel('اسم الشكل').fill('ABC')
  await button('إدراج الرسم').click()
  await page.getByLabel('حجم خط السؤال',{exact:true}).selectOption('28')
  await button('خط عريض: السؤال').click()
  await page.getByLabel('نوع السؤال').selectOption('اختيار من متعدد')
  await button('إضافة خيار').click()
  await page.getByLabel('الخيار 1').fill('الخيار الأول')
  await page.getByLabel('حجم خط الخيارات').selectOption('18')
  await button('خط عريض: الخيارات').click()
  await button('إضافة فرع للسؤال').click()
  await page.getByRole('textbox',{name:'نص الفرع 1'}).fill('عرّف العدد الزوجي.')
  await page.getByLabel('حجم خط الفرع 1').selectOption('24')
  await button('خط عريض: الفرع 1').click()
  await button('إضافة فرع للسؤال').click()
  await page.getByRole('textbox',{name:'نص الفرع 2'}).fill(('سطر طويل باللغة العربية مع English وx=4. ').repeat(550))
  await page.waitForFunction(()=>document.querySelectorAll('.print-root [data-sheet]').length>=2)
  const count=await page.locator('.print-root [data-sheet]').count()
  assert.ok((await page.locator('.print-root [data-sheet]').first().innerText()).includes('سطر طويل'))
  assert.ok(count>=2)
  for(const [value,size] of [['احسب القيمة',28],['الخيار الأول',18],['عرّف العدد الزوجي.',24]]){
    const text=page.locator('.print-root .sheet-rich').filter({hasText:value}).first()
    assert.equal(await text.evaluate(element=>getComputedStyle(element).fontSize),size+'px')
    assert.equal(await text.evaluate(element=>getComputedStyle(element).fontWeight),'700')
  }
  await button('حفظ').click()
  await page.getByText('تم الحفظ',{exact:true}).waitFor()
  if(process.env.TEST_OUTPUT){await mkdir(process.env.TEST_OUTPUT,{recursive:true});await page.screenshot({path:process.env.TEST_OUTPUT+'/editor.png'})}
  await page.reload()
  await page.getByLabel('عنوان الورقة المطبوع').waitFor()
  assert.equal(await page.getByLabel('عنوان الورقة المطبوع').inputValue(),'امتحان الرياضيات')
  await page.locator('.editable [data-equation]').first().waitFor()
  assert.equal(await page.locator('.editable table').count(),1)
  assert.equal(await page.getByAltText('الرسم الهندسي 1').count(),1)
  assert.equal(await page.getByLabel('حجم خط السؤال',{exact:true}).inputValue(),'28')
  assert.equal(await page.getByLabel('حجم خط الفرع 1').inputValue(),'24')
  assert.equal(await page.getByLabel('حجم خط الخيارات').inputValue(),'18')
  assert.equal(await button('خط عريض: الفرع 1').getAttribute('aria-pressed'),'true')
  await page.locator('.question-actions summary').click()
  await button('حفظ في بنك الأسئلة').click()
  await page.getByLabel('الفصل أو الوحدة').fill('الجبر')
  await button('حفظ السؤال').click()
  await page.getByText('تم حفظ السؤال في البنك.').waitFor()

  const exported={}
  for(const [format,scope] of [['pdf','all'],['docx','all'],['png','single'],['jpeg','all']]){
    await button('تصدير').click()
    await page.getByLabel('نوع الملف').selectOption(format)
    if(scope==='single')await page.getByLabel('نطاق التصدير').selectOption(scope)
    const result=page.waitForEvent('download',{timeout:65000})
    await button('تنزيل الملف').click()
    const download=await result
    const contents=await write(download)
    exported[format]=contents
    if(process.env.TEST_OUTPUT)await writeFile(process.env.TEST_OUTPUT+'/'+download.suggestedFilename(),contents)
    await button('إغلاق').click()
  }
  assert.equal(exported.pdf.subarray(0,4).toString(),'%PDF')
  assert.equal((exported.pdf.toString('latin1').match(/\/Type \/Page\b/g)||[]).length,count)
  assert.equal(exported.png.subarray(1,4).toString(),'PNG')
  assert.ok(exported.png.length>15_000,'PNG contains visible exam content')
  const jpeg=await JSZip.loadAsync(exported.jpeg)
  assert.equal(Object.keys(jpeg.files).length,count)
  const first=await jpeg.file('page-001.jpg').async('nodebuffer')
  assert.equal(first[0],0xff)
  assert.equal(first[1],0xd8)
  const word=await JSZip.loadAsync(exported.docx)
  const xml=await word.file('word/document.xml').async('string')
  assert.ok(xml.includes('w:bidi')&&xml.includes('احسب')&&xml.includes('w:tbl')&&xml.includes('<m:oMath>')&&xml.includes('<m:f>'))
  const wordRuns=xml.match(/<w:r>.*?<\/w:r>/gs)??[]
  for(const [value,size] of [['احسب',42],['الخيار',27],['عرّف',36]]){
    const run=wordRuns.find(item=>item.includes(value))
    assert.ok(run?.includes(`<w:szCs w:val="${size}"/>`)&&run.includes('<w:bCs/>'),value)
  }
  const headerRow=xml.match(/<w:tr>.*?<\/w:tr>/s)?.[0]??''
  const headerCells=headerRow.match(/<w:tc>.*?<\/w:tc>/gs)??[]
  assert.equal(headerCells.length,3)
  for(const cell of headerCells){
    const alignments=[...cell.matchAll(/<w:jc w:val="([^"]+)"\/>/g)].map(match=>match[1])
    assert.ok(alignments.length>0&&alignments.every(value=>value==='center'))
  }
  assert.ok(Object.keys(word.files).filter(path=>path.endsWith('.png')).length>=2)

  const printed=await page.pdf({preferCSSPageSize:true,printBackground:true})
  if(process.env.TEST_OUTPUT)await writeFile(process.env.TEST_OUTPUT+'/printed.pdf',printed)
  assert.equal((printed.toString('latin1').match(/\/Type \/Page\b/g)||[]).length,count)
  const manifest=await (await page.request.get(new URL('manifest.webmanifest',base).href)).json()
  assert.equal(manifest.display,'standalone')
  assert.ok(manifest.icons.some(icon=>icon.purpose==='maskable'))
  for(const icon of manifest.icons)assert.ok((await page.request.get(new URL(icon.src,base).href)).ok())
  await page.evaluate(()=>navigator.serviceWorker.ready)
  await context.setOffline(true)
  await page.reload()
  await page.getByLabel('عنوان الورقة المطبوع').waitFor()
  await context.setOffline(false)

  const examUrl=page.url()
  const navigate=label=>page.getByRole('link',{name:label,exact:true}).first().click()
  await navigate('الإعدادات')
  const backupDownload=page.waitForEvent('download')
  await button('تنزيل نسخة احتياطية').click()
  const backup=await write(await backupDownload)
  assert.equal(JSON.parse(backup).bank[0].chapter,'الجبر')
  await navigate('أوراقي المحفوظة')
  await button('خيارات امتحان الرياضيات').click()
  await button('حذف').click()
  await page.getByText('لا توجد أوراق امتحانية بعد',{exact:true}).waitFor()
  await navigate('الإعدادات')
  await page.locator('.panel').filter({hasText:'النسخ الاحتياطي والاستعادة'}).locator('input[type=file]').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:backup})
  await page.getByText('تمت استعادة النسخة الاحتياطية.',{exact:true}).waitFor()
  await page.goto(examUrl)
  assert.equal(await page.getByLabel('عنوان الورقة المطبوع').inputValue(),'امتحان الرياضيات')

  await page.setViewportSize({width:390,height:844})
  await button('معاينة').click()
  await page.locator('.preview-toolbar').getByText('معاينة الورقة',{exact:false}).waitFor()
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
  await page.goto(base)
  await button('إنشاء ورقة امتحانية جديدة').click()
  const mobileTitle=page.getByLabel('عنوان الورقة المطبوع')
  await mobileTitle.fill('اختبار العلوم')
  if(process.env.TEST_OUTPUT)await page.screenshot({path:process.env.TEST_OUTPUT+'/mobile-start.png',fullPage:true})
  await button('الانتقال إلى الأسئلة').click()
  await button('إضافة أول سؤال').click()
  const firstQuestion=page.getByRole('textbox',{name:'نص السؤال',exact:true}).first()
  assert.ok(await firstQuestion.evaluate(element=>document.activeElement===element))
  await page.keyboard.insertText('ما أهمية الماء؟')
  await button('إضافة سؤال آخر').click()
  const secondQuestion=page.getByRole('textbox',{name:'نص السؤال',exact:true}).nth(1)
  assert.ok(await secondQuestion.evaluate(element=>document.activeElement===element))
  await page.keyboard.insertText('اذكر حالات الماء.')
  const mobileLayout=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:innerWidth,overflow:Array.from(document.querySelectorAll('body *')).filter(element=>element.getBoundingClientRect().right>innerWidth+1).slice(0,15).map(element=>[element.className,element.getBoundingClientRect().right])}))
  assert.ok(mobileLayout.width<=mobileLayout.viewport+1,JSON.stringify(mobileLayout))
  if(process.env.TEST_OUTPUT)await page.screenshot({path:process.env.TEST_OUTPUT+'/mobile-editor.png'})
  await button('معاينة الورقة قبل الطباعة').click()
  await page.locator('.preview-viewport').getByText('اختبار العلوم',{exact:true}).waitFor()
  await page.locator('.preview-viewport').getByText('اذكر حالات الماء.',{exact:true}).waitFor()
  if(process.env.TEST_OUTPUT)await page.screenshot({path:process.env.TEST_OUTPUT+'/mobile.png',fullPage:true})
  assert.deepEqual(errors,[])
  console.log(`PASS Chromium: RTL, math, table, SVG, IndexedDB backup and restore, question bank, ${count} pages, PDF, DOCX, PNG, JPEG ZIP, printing, offline PWA, mobile viewport.`)
} finally {
  await browser?.close()
  await new Promise((resolve,reject)=>server.httpServer.close(error=>error?reject(error):resolve()))
}
